const getLang = () => localStorage.getItem('lang') || 'es';

const t = (key) => I18N[getLang()][key] || key;

const swapText = (lang) => {
  localStorage.setItem('lang', lang);
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    const text = I18N[lang][key];
    if (text === undefined) return;
    el.textContent = text;
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    const key = el.getAttribute('data-i18n-aria');
    const text = I18N[lang][key];
    if (text !== undefined) el.setAttribute('aria-label', text);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    const text = I18N[lang][key];
    if (text !== undefined) el.setAttribute('placeholder', text);
  });
  document.querySelectorAll('[data-lang-switch]').forEach((btn) => {
    btn.setAttribute('aria-pressed', btn.dataset.langSwitch === lang ? 'true' : 'false');
  });
};

// ponytail: fade out -> swap -> fade in. 180ms matches the transition in styles.css.
// First call on page load skips the fade because the DOM is already in the right language.
let _swapTimer = null;
let _firstSwap = true;
const applyLang = (lang) => {
  if (_swapTimer) return;
  if (_firstSwap) {
    _firstSwap = false;
    swapText(lang);
    return;
  }
  const html = document.documentElement;
  html.classList.add('i18n-swapping');
  _swapTimer = setTimeout(() => {
    swapText(lang);
    requestAnimationFrame(() => {
      html.classList.remove('i18n-swapping');
    });
    _swapTimer = null;
  }, 180);
};

document.addEventListener('DOMContentLoaded', () => {
  applyLang(getLang());
  document.querySelectorAll('[data-lang-switch]').forEach((btn) => {
    btn.addEventListener('click', () => applyLang(btn.dataset.langSwitch));
  });
});
